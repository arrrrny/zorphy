import 'package:path/path.dart' as p;

import '../models/entity_config.dart';

/// Generates entity template code
class EntityTemplateGenerator {
  const EntityTemplateGenerator._();

  /// Escapes a string value for safe interpolation into a Dart string
  /// literal. Handles apostrophes, backslashes, quotes, dollar signs, and
  /// line breaks. Mirrors `escapeDartStringLiteral` in json_generator.dart.
  static String escapeDartStringLiteral(String value) {
    return value
        .replaceAll('\\', '\\\\') // backslash must be first
        .replaceAll("'", "\\'") // single quote
        .replaceAll('"', '\\"') // double quote
        .replaceAll('\$', '\\\$') // dollar sign
        .replaceAll('\n', '\\n') // newline
        .replaceAll('\r', '\\r') // carriage return
        .replaceAll('\t', '\\t'); // tab
  }

  /// Generate entity file content
  static String generate(EntityConfig config, List<String> imports) {
    final buffer = StringBuffer();

    _writeHeader(buffer);
    _writeImports(buffer, imports);
    _writePartDirective(buffer, config);
    _writeClassDefinition(buffer, config);

    return buffer.toString();
  }

  /// Generate subtype entity file content
  static String generateSubtype(
    EntityConfig parentConfig,
    EntityConfig subtypeConfig,
    String parentClassName,
    bool isSealed,
    List<String> imports,
  ) {
    final buffer = StringBuffer();

    _writeHeader(buffer);
    _writeImports(buffer, imports);
    _writePartDirective(buffer, subtypeConfig);
    _writeSubtypeClassDefinition(
      buffer,
      subtypeConfig,
      parentClassName,
      isSealed,
    );

    return buffer.toString();
  }

  static void _writeHeader(StringBuffer buffer) {
    buffer.writeln('// Auto-generated by Zorphy');
    buffer.writeln('// Generated at: ${DateTime.now().toIso8601String()}');
    buffer.writeln();
  }

  static void _writeImports(StringBuffer buffer, List<String> imports) {
    buffer.writeln(
      "import 'package:zorphy_annotation/zorphy_annotation.dart';",
    );

    if (imports.isNotEmpty) {
      final sorted = imports.toList()..sort();
      for (final import in sorted) {
        buffer.writeln(import);
      }
    }
    buffer.writeln();
  }

  static void _writePartDirective(StringBuffer buffer, EntityConfig config) {
    buffer.writeln("part '${sharedPartUri(config)}';");
    buffer.writeln();
  }

  /// The `part` URI of the v3 shared part for [config]'s library (issue #297).
  ///
  /// The v3 builder contributes to a shared part: build_runner writes
  /// `<library>.part.dart` in its reserved `_br_` namespace, mirroring the
  /// library's own path (`lib/a/b.dart` gets `lib/_br_/a/b.part.dart`, and
  /// a library outside `lib/` gets `_br_/a/b.part.dart` at the package
  /// root). No standalone `<name>.zorphy.dart` is ever written, so a
  /// scaffold pointing at the v2 filename never compiles.
  ///
  /// [EntityConfig.outputDir] is read package-relative. The caller
  /// (`EntityCreator`) resolves an on-disk output path to a package-relative
  /// dir before generating, so this method stays a pure function of its
  /// inputs — it never touches the filesystem. An absolute path handed to
  /// this method directly is rebased on its last `lib` segment (the only
  /// rebase that can be done without filesystem knowledge).
  static String sharedPartUri(EntityConfig config) {
    var output = (config.outputDir ?? config.defaultOutputDir).replaceAll(
      r'\',
      '/',
    );
    if (p.posix.isAbsolute(output) || RegExp(r'^[A-Za-z]:').hasMatch(output)) {
      final segments = p.posix.split(p.posix.normalize(output));
      final libIndex = segments.lastIndexOf('lib');
      output = libIndex >= 0
          ? p.posix.joinAll(segments.sublist(libIndex))
          : '';
    }
    final library = p.posix.normalize(
      p.posix.join(output, config.snakeName, '${config.snakeName}.dart'),
    );
    final segments = p.posix.split(library);
    final isLib = segments.first == 'lib';
    final dir = segments.sublist(0, segments.length - 1);
    final part = p.posix.joinAll([
      if (isLib) ...['lib', '_br_'] else '_br_',
      ...dir.sublist(isLib ? 1 : 0),
      '${config.snakeName}.part.dart',
    ]);
    return p.url.relative(part, from: p.posix.joinAll(dir));
  }

  static void _writeClassDefinition(StringBuffer buffer, EntityConfig config) {
    final annotation = _buildAnnotation(config);

    buffer.writeln('/// ${config.className} entity');
    buffer.writeln(annotation);

    final abstractClassName = config.isSealed || config.isNonSealed
        ? '\$\$${config.className}'
        : '\$${config.className}';

    if (config.extendsInterface != null) {
      // Issue #304 fix: normalize the extends interface to use the
      // `$`-prefixed source abstract class name. The user passes the
      // public concrete class name (e.g., `AuthenticationResult`), but
      // the source abstract class that the analyzer can resolve is
      // `$AuthenticationResult`. Without the `$` prefix, the analyzer
      // silently drops the implements clause (the concrete class doesn't
      // exist at source-analysis time), and the generated concrete class
      // loses the implements clause — breaking `isA<Base>()` checks.
      //
      // If the user already passed a `$`-prefixed name (e.g., `$$Shape`
      // for a sealed class), use it as-is.
      final extendsInterface = _normalizeExtendsInterface(
        config.extendsInterface!,
      );
      buffer.writeln(
        'abstract class $abstractClassName implements $extendsInterface {',
      );
    } else {
      buffer.writeln('abstract class $abstractClassName {');
    }
    buffer.writeln();

    _writeFields(buffer, config.fields, prependAutoId: _ownsIdentity(config));

    _writeStatics(buffer, config.staticMembers);

    buffer.writeln('}');
    buffer.writeln();
  }

  static void _writeSubtypeClassDefinition(
    StringBuffer buffer,
    EntityConfig config,
    String parentClassName,
    bool parentIsSealed,
  ) {
    buffer.writeln(
      '/// ${config.className} entity (subtype of $parentClassName)',
    );
    buffer.writeln('@ZorphyValue()');

    final parentRef = parentIsSealed || config.isNonSealed
        ? '\$\$$parentClassName'
        : '\$$parentClassName';
    buffer.writeln(
      'abstract class \$${config.className} implements $parentRef {',
    );

    if (config.fields.isNotEmpty) {
      buffer.writeln();
      _writeFields(buffer, config.fields);
    }

    buffer.writeln('}');
    buffer.writeln();
  }

  /// Normalize the extends interface name to use the `$`-prefixed source
  /// abstract class name.
  ///
  /// - `AuthenticationResult` → `\$AuthenticationResult`
  /// - `\$AuthenticationResult` → `\$AuthenticationResult` (no change)
  /// - `\$\$Shape` → `\$\$Shape` (no change, sealed class)
  ///
  /// This ensures the analyzer can resolve the implements target at
  /// source-analysis time (the source abstract class exists; the generated
  /// concrete class does not).
  static String _normalizeExtendsInterface(String name) {
    if (name.startsWith(r'$')) return name;
    return '\$$name';
  }

  /// Builds the v3 archetype annotation for [config].
  ///
  /// The v3 surface is zero-toggle (issue #233): a sealed class is a
  /// `@ZorphyUnion`, an entity with its own identity is an
  /// `@ZorphyEntity(principalKey: #id)`, and everything else is a
  /// `@ZorphyValue`. The legacy `generate*` / `kind` / `autoId` /
  /// `typeKey` toggles are gone.
  static String _buildAnnotation(EntityConfig config) {
    if (config.isSealed) return '@ZorphyUnion()';
    if (config.kind == ZorphyKind.entity) {
      return '@ZorphyEntity(principalKey: #id)';
    }
    return '@ZorphyValue()';
  }

  /// Whether this scaffold is a root `@ZorphyEntity`, whose annotation
  /// promises `principalKey: #id` (issue #297).
  ///
  /// Identity is not a toggle: the field is declared even when the
  /// caller listed none, because the v3 diagnostics (`ZORPHY_E001`)
  /// reject a key that names no field. A class implementing another
  /// interface inherits its identity instead, so an inherited getter is
  /// never redeclared.
  static bool _ownsIdentity(EntityConfig config) =>
      !config.isSealed &&
      config.kind == ZorphyKind.entity &&
      config.extendsInterface == null;

  /// Generate inline subtype (for sealed classes)
  static String generateInlineSubtype(
    String subtypeName,
    String parentClassName,
    bool parentIsSealed,
    List<FieldDefinition> fields,
    EntityConfig parentConfig,
  ) {
    final buffer = StringBuffer();

    buffer.writeln('/// $subtypeName entity (subtype of $parentClassName)');
    buffer.writeln('@ZorphyValue()');

    final parentRef = parentIsSealed || parentConfig.isNonSealed
        ? '\$\$$parentClassName'
        : '\$$parentClassName';
    buffer.writeln('abstract class \$$subtypeName implements $parentRef {');

    if (fields.isNotEmpty) {
      buffer.writeln();
      _writeFields(buffer, fields);
    }

    buffer.writeln('}');
    buffer.writeln();

    return buffer.toString();
  }

  /// Emits static final class members in "name:type:value" format.
  static void _writeStatics(StringBuffer buffer, List<String> staticMembers) {
    for (final entry in staticMembers) {
      final firstColon = entry.indexOf(':');
      final secondColon = entry.indexOf(':', firstColon + 1);
      if (firstColon < 0 || secondColon < 0) continue;
      final name = entry.substring(0, firstColon).trim();
      final type = entry.substring(firstColon + 1, secondColon).trim();
      final value = entry.substring(secondColon + 1).trim();
      buffer.writeln('  static final $type $name = $value;');
    }
    if (staticMembers.isNotEmpty) buffer.writeln();
  }

  /// Writes the getter declarations for [fields], emitting an
  /// `@JsonKey(name: ...)` annotation above a getter when the field's
  /// [FieldDefinition.jsonName] differs from its Dart [FieldDefinition.name].
  ///
  /// When [prependAutoId] is true and no field is named `id`, the
  /// `String get id;` identity field is written first.
  static void _writeFields(
    StringBuffer buffer,
    List<FieldDefinition> fields, {
    bool prependAutoId = false,
  }) {
    final hasIdField = fields.any((f) => f.name == 'id');
    if (prependAutoId && !hasIdField) {
      buffer.writeln('  String get id;');
    }
    for (final field in fields) {
      if (field.jsonName != null) {
        buffer.writeln(
          "  @JsonKey(name: '${escapeDartStringLiteral(field.jsonName!)}')",
        );
      }
      buffer.writeln('  ${field.fullType} get ${field.name};');
    }
  }
}
